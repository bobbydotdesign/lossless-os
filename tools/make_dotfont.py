"""Write app/dotfont.h: the dot-matrix glyphs as bit rows.

The glyphs are drawn once, in the lossless theme's make_dot_font.py (5 x 7
grid plus a descender row), and shared by the Lossless themes and Lossless OS.

usage: python3 tools/make_dotfont.py [path to make_dot_font.py]

SPDX-License-Identifier: Apache-2.0
"""
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT = os.path.join(os.path.dirname(os.path.dirname(HERE)), "theme", "tools", "make_dot_font.py")


def main(src):
    spec = importlib.util.spec_from_file_location("dotfont", src)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    glyphs = mod.GLYPHS
    out = ["/* Generated by tools/make_dotfont.py from theme/tools/make_dot_font.py.",
           " * Each glyph: its width in dots and 8 rows, bit 0 = leftmost dot.",
           " *", " * SPDX-License-Identifier: Apache-2.0", " */",
           "#ifndef LOS_DOTFONT_H", "#define LOS_DOTFONT_H", "", "#include <stdint.h>", "",
           "typedef struct { char ch; uint8_t width; uint8_t rows[8]; } los_dotglyph;", "",
           "static const los_dotglyph los_dotfont[] = {"]
    for ch, rows in sorted(glyphs.items(), key=lambda kv: ord(kv[0])):
        rows = rows + ["." * len(rows[0])] * (8 - len(rows))
        bits = []
        for r in rows:
            v = 0
            for i, c in enumerate(r):
                if c == "#":
                    v |= 1 << i
            bits.append(f"0x{v:02x}")
        esc = "\\\\" if ch == "\\" else ("\\'" if ch == "'" else ch)
        out.append(f"    {{ '{esc}', {len(rows[0])}, {{ {', '.join(bits)} }} }},")
    out += ["};", "", "#endif", ""]
    path = os.path.join(os.path.dirname(HERE), "app", "dotfont.h")
    open(path, "w").write("\n".join(out))
    print(f"wrote {path}: {len(glyphs)} glyphs")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else DEFAULT)
