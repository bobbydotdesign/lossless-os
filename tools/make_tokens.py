"""Write app/tokens.h from the Lossless app's design tokens.

The app's packages/design/src/index.ts is the one source for colours and
corner sizes; the phone app, the web app, the themes and Lossless OS all
take them from there.

usage: python3 tools/make_tokens.py [path to lossless/packages/design/src/index.ts]

SPDX-License-Identifier: Apache-2.0
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT = os.path.expanduser("~/Claude-Projects/lossless/packages/design/src/index.ts")


def parse(src):
    text = open(src).read()
    palettes = {}
    for scheme in ("light", "dark"):
        block = re.search(scheme + r":\s*\{(.*?)\n  \}", text, re.S).group(1)
        palettes[scheme] = re.findall(r"(\w+):\s*'#([0-9a-fA-F]{6})'", block)
    shape = dict(re.findall(r"(surface|control|inset):\s*(\d+)", text))
    return palettes, shape


def main(src):
    palettes, shape = parse(src)
    keys = [k for k, _ in palettes["dark"]]
    out = ["/* Generated by tools/make_tokens.py from lossless/packages/design.",
           " * Don't edit: change the design tokens and run the tool.",
           " *", " * SPDX-License-Identifier: Apache-2.0", " */",
           "#ifndef LOS_TOKENS_H", "#define LOS_TOKENS_H", "", "#include <stdint.h>", "",
           "typedef struct {"]
    out += [f"    uint32_t {k};" for k in keys]
    out += ["} los_palette;", ""]
    for scheme, name in (("dark", "graphite"), ("light", "aluminium")):
        vals = dict(palettes[scheme])
        out.append(f"static const los_palette los_{name} = {{")
        out += [f"    .{k} = 0x{vals[k].upper()}," for k in keys if k in vals]
        out.append("};")
        out.append("")
    # corner radii are in phone points; the H2's screen is about half that
    for k, v in shape.items():
        out.append(f"#define LOS_RADIUS_{k.upper()} {max(int(v) // 2, 2)}  /* app: {v} pt */")
    out += ["", "#endif", ""]
    path = os.path.join(os.path.dirname(HERE), "app", "tokens.h")
    open(path, "w").write("\n".join(out))
    print(f"wrote {path}: {len(keys)} colours, {len(shape)} radii")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else DEFAULT)
